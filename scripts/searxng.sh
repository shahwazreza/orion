#!/usr/bin/env bash
# Local SearXNG for Orion's web search: rootless Podman, reachable ONLY from this
# computer (127.0.0.1), never from the network (dorm rule: no open ports).
#
#   scripts/searxng.sh start | stop | status | logs
#
# Config lives outside the repo in ~/.config/orion/searxng/ (it holds a random
# secret generated on first start).
set -euo pipefail

NAME=orion-searxng
IMAGE=docker.io/searxng/searxng:2026.10.24-ef0ec03da@sha256:7c7cbe509429e82755104b2a95f52085a98633c95d53f44e4e905fa3a59f08c8   # pinned tag + digest; update both together
PORT=8888
CONF="${XDG_CONFIG_HOME:-$HOME/.config}/orion/searxng"

write_settings() {
  if [ -d "$CONF" ] && [ ! -O "$CONF" ]; then
    return 0    # already set up and handed to the container's user (see below)
  fi
  mkdir -p "$CONF"
  if [ ! -f "$CONF/settings.yml" ]; then
    secret=$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')
    cat > "$CONF/settings.yml" <<EOF
# Orion's local SearXNG. Generated by scripts/searxng.sh.
use_default_settings: true
general:
  instance_name: orion-local
server:
  secret_key: "$secret"
  limiter: false            # only this computer can reach it
  image_proxy: false
  bind_address: "0.0.0.0"   # inside the container; the host side is published on 127.0.0.1 only
search:
  safe_search: 0
  formats: [html, json]     # Orion reads JSON
ui:
  query_in_title: false
EOF
  fi
  # The image's entrypoint starts as the container's root (= you on the host) and then
  # runs SearXNG as uid 977 (one of your subordinate IDs). Both must read the config, so
  # it's owned by 977 and world-readable (755/644). The secret in it only signs SearXNG's
  # own web sessions, which Orion doesn't use.
  # Edit it later with: podman unshare nano "$CONF/settings.yml"
  chmod 755 "$CONF" && chmod 644 "$CONF/settings.yml"
  podman unshare chown -R 977:977 "$CONF"
}

case "${1:-status}" in
  start)
    write_settings
    podman run -d --replace --name "$NAME" \
      -p "127.0.0.1:${PORT}:8080" \
      -v "$CONF:/etc/searxng:Z" \
      --cap-drop ALL --cap-add CHOWN --cap-add SETGID --cap-add SETUID \
      "$IMAGE" >/dev/null
    echo "SearXNG started on http://127.0.0.1:${PORT} (this computer only)"
    ;;
  stop)
    podman rm -f "$NAME" >/dev/null 2>&1 && echo "SearXNG stopped" || echo "SearXNG wasn't running"
    ;;
  status)
    if podman container exists "$NAME" && [ "$(podman inspect -f '{{.State.Running}}' "$NAME")" = "true" ]; then
      echo "running: $(podman port "$NAME" | tr '\n' ' ')"
    else
      echo "not running (start with: scripts/searxng.sh start)"
    fi
    ;;
  logs)
    podman logs --tail 50 "$NAME"
    ;;
  *)
    echo "usage: $0 start|stop|status|logs" >&2; exit 2 ;;
esac
